package com.unihub.app.feature.files

/**
 * يتحكم في «سحب لإظهار» بطاقة ملخص السحابة (الهيدر) أعلى قائمة الملفات السحابية.
 *
 * المشكلة المُصلَحة (بلاغ المستخدم مع صورة توضيحية بمربعين):
 * - المربع الأحمر (بطاقة «مكتبة الملفات السحابية») كانت تُعرض دائماً أعلى
 *   الشاشة فتأكل مساحة القائمة الحقيقية (المربع الأزرق).
 * - المطلوب: الهيدر **مخفي افتراضياً** (ارتفاعه صفر — غير محذوف من الشجرة)
 *   وتُصبح القائمة هي أول ما يظهر أسفل الشريط العلوي مباشرة.
 * - الهيدر يظهر فقط عند الوصول لأعلى القائمة (لا مزيد من العناصر فوقها)
 *   ثم الاستمرار بنفس حركة «السحب للأسفل» (overscroll)، تماماً كسحب التحديث.
 * - أي تمرير طبيعي للمحتوى نحو الأسفل (لرؤية عناصر لاحقة) يُخفي الهيدر أولاً
 *   بنفس القدر قبل أن تتحرك القائمة نفسها — فتظهر وتختفي بنفس حركة الإصبع.
 *
 * الصنف مستقل تماماً عن Compose وAndroid (بلا أي استيراد منهما) ليكون قابلاً
 * للاختبار بوحدات JVM خالصة (JUnit عادي) بلا حاجة لمحاكي أو موارد أندرويد —
 * القرار منطقي بحت: كمية بكسلات مستهلكة من حركة تمرير معطاة.
 *
 * تُستخدم القيم بنفس اصطلاح Compose لـ NestedScrollConnection: إشارة موجبة
 * على المحور Y تعني أن الإصبع يتحرك نحو الأسفل (المحتوى ينزلق للأسفل، أي
 * «سحب لإظهار عناصر سابقة» / سحب للتحديث)، وإشارة سالبة تعني تمريراً نحو
 * الأسفل في المحتوى (رؤية عناصر لاحقة).
 */
class CloudHeroRevealController(
    val maxOffsetPx: Float
) {
    init {
        require(maxOffsetPx >= 0f) { "maxOffsetPx يجب أن يكون صفراً أو أكبر، كانت القيمة $maxOffsetPx" }
    }

    /** كمية الإظهار الحالية بالبكسل: 0 = مخفي تماماً، [maxOffsetPx] = ظاهر كلياً. */
    var offsetPx: Float = 0f
        private set

    /** ظاهر ولو جزئياً. */
    val isRevealed: Boolean get() = offsetPx > 0f

    /** ظاهر بالكامل (بلغ الحد الأقصى المتاح). */
    val isFullyRevealed: Boolean get() = maxOffsetPx > 0f && offsetPx >= maxOffsetPx

    /** نسبة الإظهار بين 0f و1f، لربط الشفافية/الانزلاق بها أثناء السحب المباشر. */
    val fraction: Float get() = if (maxOffsetPx <= 0f) 0f else (offsetPx / maxOffsetPx).coerceIn(0f, 1f)

    /**
     * يُستدعى من onPreScroll — أي *قبل* أن تستهلك القائمة الحركة.
     * إن كانت الحركة تمرير محتوى عادي نحو الأسفل (deltaY سالب) وكان الهيدر
     * ظاهراً جزئياً أو كلياً، نُخفيه تدريجياً بقدر الحركة أولاً — قبل أن تمس
     * القائمة ذاتها — فتبدو الحركة متصلة بلا قفزة. نُرجع الكمية المُستهلَكة
     * (سالبة أو صفر) ليخصمها المستدعي من الحركة المتاحة للقائمة.
     */
    fun onPreScroll(deltaY: Float): Float {
        if (deltaY < 0f && offsetPx > 0f) {
            val consumed = (-offsetPx).coerceAtLeast(deltaY)
            offsetPx += consumed
            return consumed
        }
        return 0f
    }

    /**
     * يُستدعى من onPostScroll — بعد أن عجزت القائمة عن استهلاك مزيد من الحركة
     * (بلغت فعلياً أول عنصر فيها، أي لا مزيد من التمرير للأعلى ممكن داخلها).
     * إن كان المتبقي استمراراً لنفس سحب «إظهار الهيدر» (leftoverY موجب) نزيد
     * ظهوره بقدره، محدوداً بـ[maxOffsetPx]. نُرجع الكمية المُستهلَكة فعلياً.
     */
    fun onPostScroll(leftoverY: Float): Float {
        if (leftoverY > 0f) {
            val target = (offsetPx + leftoverY).coerceIn(0f, maxOffsetPx)
            val consumed = target - offsetPx
            offsetPx = target
            return consumed
        }
        return 0f
    }

    /** يُعيد الهيدر فوراً لحالته المخفية الافتراضية (بلا انيميشن) — مثلاً عند تغيير المجلد. */
    fun reset() {
        offsetPx = 0f
    }

    /**
     * عتبة الإفلات: عند رفع الإصبع في منتصف السحب، نقرّر إن كان يُكمل للظهور
     * الكامل أم يعود للاختفاء — نحو أقرب طرف، كما في أي «سحب للتحديث» مألوف.
     * تُرجع القيمة الجديدة لـ[offsetPx] بعد الاستقرار.
     */
    fun settle(): Float {
        offsetPx = if (fraction >= 0.5f) maxOffsetPx else 0f
        return offsetPx
    }
}
